// Program 15: Write a java program to print first 50 number.

class Program15 {
    public static void main(String args[]) {
        System.out.println("First 50 numbers:");
        for (int i = 1; i <= 50; i++) {
            System.out.print(i + " ");
        }
        System.out.println();
    }
}
